#!/usr/bin/env python3
"""7kmod-fryhtan: generate include/ModSmoothText.h, the smooth (anti-aliased)
texts of the New Game screen: the names of the Fryhtan species, the tabs
Humans / Fryhtans and the label "Seats of Power Unlocked?".

They are drawn with TeX Gyre Pagella Bold Italic (a free font, GUST Font
License, a Palatino clone; also Italic for the tabs not chosen), 4x size
and reduced, so they look like the race names of the original artwork.

Each pixel is stored as a darkening level 0-10: the game draws the text by
darkening the background with its color tables
(vga.vga_color_table->get_table(-level)), which keeps the 256-color
palette. Level 10 is black.

Usage: python3 7kmod/tools/make_smooth_text.py [font dir]
Needs Pillow. The default font dir is the one of TeX Live (Debian/Ubuntu
package tex-gyre).
"""
import sys, os
from PIL import Image, ImageDraw, ImageFont

FONT_DIR = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/texmf/fonts/opentype/public/tex-gyre'
BOLD = os.path.join(FONT_DIR, 'texgyrepagella-bolditalic.otf')
REGULAR = os.path.join(FONT_DIR, 'texgyrepagella-italic.otf')

SPECIES = ['Deezboanz', 'Rattus', 'Broosken', 'Haubudam', 'Pfith', 'Rokken', 'Doink',
           'Wyrm', 'Droog', 'Ick', 'Sauroid', 'Karrotten', 'Holgh']
SPECIES_MAX_WIDTH = 78 - 12          # a species button is 78 pixels wide
LABEL_SIZE = 16                      # the size of the tabs and the labels (pixels)
SCALE = 4
MAX_LEVEL = 10


def species_size():
    size = 19
    while size > 10:
        f = ImageFont.truetype(BOLD, size * SCALE)
        if max(f.getlength(n) / SCALE for n in SPECIES) <= SPECIES_MAX_WIDTH:
            return size
        size -= 1
    return size


def render(text, fontPath, size, boost=1.0):
    """Return (width, height, levels): the text box of the line ('Hg' high)."""
    f = ImageFont.truetype(fontPath, size * SCALE)
    asc, desc = f.getmetrics()
    lineBox = f.getbbox('Hg')
    textBox = f.getbbox(text)
    pad = SCALE * 2
    x1 = min(textBox[0], 0) - pad
    x2 = textBox[2] + pad
    y1 = lineBox[1] - pad
    y2 = lineBox[3] + pad
    w = (x2 - x1 + SCALE - 1) // SCALE * SCALE
    h = (y2 - y1 + SCALE - 1) // SCALE * SCALE
    img = Image.new('L', (w, h), 0)
    ImageDraw.Draw(img).text((-x1, -y1), text, font=f, fill=255)
    small = img.resize((w // SCALE, h // SCALE), Image.BOX)
    # trim the empty columns
    px = small.load()
    W, H = small.size
    cols = [x for x in range(W) if any(px[x, y] for y in range(H))]
    if cols:
        small = small.crop((cols[0], 0, cols[-1] + 1, H))
    W, H = small.size
    px = small.load()
    levels = []
    for y in range(H):
        for x in range(W):
            a = min(1.0, px[x, y] / 255.0 * boost)        # boost: darker strokes for the thin regular font
            # the color tables darken by sqrt((10-level)/10): level for a brightness of 1-a
            levels.append(int(round(MAX_LEVEL * (1 - (1 - a) ** 2))))
    return W, H, levels


def main():
    entries = []
    size = species_size()
    for name in sorted(SPECIES):
        entries.append((name, render(name, BOLD, size)))
    for text in ('Humans', 'Fryhtans'):
        entries.append((text, render(text, BOLD, LABEL_SIZE)))
    for text in ('Humans', 'Fryhtans', 'Seats of Power Unlocked?'):       # the tab not chosen, and the labels
        entries.append((text + '#', render(text, REGULAR, LABEL_SIZE, 1.7)))

    out = []
    out.append('// 7kmod-fryhtan: generated by 7kmod/tools/make_smooth_text.py, do not edit.')
    out.append('// Smooth texts (TeX Gyre Pagella, GUST Font License): darkening level 0-10 per pixel.')
    out.append('// A key ending in "#" is the regular (not bold) version.')
    out.append('')
    out.append('#ifndef __MODSMOOTHTEXT_H')
    out.append('#define __MODSMOOTHTEXT_H')
    out.append('')
    out.append('struct SmoothText { const char* text; short width, height; const unsigned char* data; };')
    out.append('')
    for i, (text, (w, h, levels)) in enumerate(entries):
        out.append('static const unsigned char smooth_text_data_%d[%d] = {  // %s' % (i, w * h, text))
        for y in range(h):
            out.append('\t' + ','.join(str(v) for v in levels[y * w:(y + 1) * w]) + ',')
        out.append('};')
    out.append('')
    out.append('static const SmoothText smooth_text_array[] =')
    out.append('{')
    for i, (text, (w, h, levels)) in enumerate(entries):
        out.append('\t{ "%s", %d, %d, smooth_text_data_%d },' % (text, w, h, i))
    out.append('};')
    out.append('')
    out.append('#endif')
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'include', 'ModSmoothText.h')
    open(path, 'w').write('\n'.join(out) + '\n')
    print('species size', size, '->', os.path.normpath(path))


main()
